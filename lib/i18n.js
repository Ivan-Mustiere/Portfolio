// UI strings for every page. French lives at the root, English under /en (same paths otherwise).

export const LOCALES = ["fr", "en"];

export function homeHref(lang) {
  return lang === "en" ? "/en" : "/";
}

export function infraHref(lang) {
  return lang === "en" ? "/en/infra" : "/infra";
}

export function projectsHref(lang, id) {
  return `${lang === "en" ? "/en" : ""}/projets${id ? `/${id}` : ""}`;
}

// Same page in the other language: "/infra" <-> "/en/infra", "/" <-> "/en"
export function otherLangPath(pathname, lang) {
  if (lang === "en") return pathname.replace(/^\/en(?=\/|$)/, "") || "/";
  return pathname === "/" ? "/en" : `/en${pathname}`;
}

// Demo config (projets/<id>/portfolio.json) is written in French; its optional `en` object overrides fields
export function localizeProject(project, lang) {
  return lang === "en" && project?.en ? { ...project, ...project.en } : project;
}

